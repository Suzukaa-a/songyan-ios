#!/usr/bin/env python3
"""Embeds a UTF-8 text file as C string literals so the bridge ships it inside the binary.

The keyboard extension cannot read a resource path the same way the command-line tool does, and
having one generated array keeps the JavaScript source a normal, reviewable file. Non-printable
bytes use three-digit octal escapes so a following digit can never extend the escape; each
literal is one slice of the source, so an escape is never split between literals.
"""

import pathlib
import sys

CHUNK = 96


def escape(chunk: bytes) -> str:
    parts = []
    for byte in chunk:
        if byte == 0x0A:
            parts.append("\\n")
        elif byte == 0x0D:
            parts.append("\\r")
        elif byte == 0x09:
            parts.append("\\t")
        elif byte in (0x22, 0x5C):
            parts.append("\\" + chr(byte))
        elif 0x20 <= byte <= 0x7E:
            parts.append(chr(byte))
        else:
            parts.append(f"\\{byte:03o}")
    return "".join(parts)


def literals(data: bytes) -> str:
    return "\n".join(
        '"' + escape(data[index:index + CHUNK]) + '"'
        for index in range(0, len(data), CHUNK)
    )


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: embed-text.py <input> <output> <c-name>", file=sys.stderr)
        return 64
    source = pathlib.Path(sys.argv[1])
    destination = pathlib.Path(sys.argv[2])
    name = sys.argv[3]
    data = source.read_bytes()
    if not data:
        print(f"embed-text: {source} is empty", file=sys.stderr)
        return 65
    body = (
        "/* Generated by Tools/Script/scripts/embed-text.py from "
        f"{source.name}; do not edit. */\n"
        f"static const char {name}[] =\n{literals(data)};\n"
        f"static const size_t {name}_length = sizeof({name}) - 1;\n"
    )
    destination.write_text(body, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
