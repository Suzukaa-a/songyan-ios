import CryptoKit
import Foundation

/// Stores scripts byte-for-byte plus one versioned JSON state per addon under a host
/// supplied root (the Host app uses the shared App Group container so the keyboard
/// extension can read the same files later).
///
/// Layout:
///   <root>/<id>/script.js     the original bytes, untouched
///   <root>/<id>/state.json    ScriptAddonState, schema versioned
public final class ScriptAddonStore: @unchecked Sendable {
    public enum StoreError: Error, Equatable {
        case unsupportedStateVersion(Int)
        case invalidIdentifier
        case scriptTooLarge(limit: Int)
        case missingScript
        case duplicateID
    }

    public struct Addon: Equatable, Sendable {
        public let state: ScriptAddonState
        public let scriptURL: URL
        public init(state: ScriptAddonState, scriptURL: URL) {
            self.state = state
            self.scriptURL = scriptURL
        }
    }

    public let root: URL
    private let fileManager: FileManager

    public init(root: URL, fileManager: FileManager = .default) {
        self.root = root
        self.fileManager = fileManager
    }

    // MARK: - Read

    public func list() throws -> [Addon] {
        let directories = try fileManager.contentsOfDirectory(
            at: root, includingPropertiesForKeys: [.isDirectoryKey], options: [.skipsHiddenFiles])
        var addons: [Addon] = []
        for directory in directories {
            guard (try? directory.resourceValues(forKeys: [.isDirectoryKey]).isDirectory) == true
            else { continue }
            if let addon = try? load(id: directory.lastPathComponent) {
                addons.append(addon)
            }
        }
        return addons.sorted {
            if $0.state.order != $1.state.order { return $0.state.order < $1.state.order }
            return $0.state.id < $1.state.id
        }
    }

    public func load(id: String) throws -> Addon {
        try validate(id)
        let scriptURL = scriptURL(id: id)
        guard fileManager.fileExists(atPath: scriptURL.path) else {
            throw StoreError.missingScript
        }
        let stateURL = stateURL(id: id)
        let data = try Data(contentsOf: stateURL)
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        let state = try decoder.decode(ScriptAddonState.self, from: data).decoded()
        return Addon(state: state, scriptURL: scriptURL)
    }

    public func scriptBytes(id: String) throws -> Data {
        try validate(id)
        return try Data(contentsOf: scriptURL(id: id))
    }

    // MARK: - Write

    /// Adds a script using exactly the bytes given. The identifier is generated by the
    /// caller so an import flow can show the confirmation page before writing.
    @discardableResult
    public func add(
        id: String, script: Data, state: ScriptAddonState, maximumSourceBytes: Int
    ) throws -> Addon {
        try validate(id)
        guard script.count <= maximumSourceBytes else {
            throw StoreError.scriptTooLarge(limit: maximumSourceBytes)
        }
        let directory = root.appendingPathComponent(id, isDirectory: true)
        let temporary = directory.appendingPathComponent("script.js.tmp")
        let scriptURL = scriptURL(id: id)
        let stateURL = stateURL(id: id)
        var updated = state
        updated.scriptDigest = Self.digest(script)
        updated.scriptByteCount = script.count
        updated.updatedAt = Date()
        try fileManager.createDirectory(at: directory, withIntermediateDirectories: true)
        try script.write(to: temporary, options: .atomic)
        // A second import of the same identifier, or an edit of an existing script,
        // writes into a script.js that is already there; moving onto it fails with
        // "File exists", so replace it in place instead.
        if fileManager.fileExists(atPath: scriptURL.path) {
            _ = try fileManager.replaceItemAt(scriptURL, withItemAt: temporary)
        } else {
            try fileManager.moveItem(at: temporary, to: scriptURL)
        }
        try writeState(updated, to: stateURL)
        return Addon(state: updated, scriptURL: scriptURL)
    }

    /// Replaces the bytes (in-app editing or a fetched update). The caller confirms the
    /// new declarations first; the digest and byte count follow the new bytes.
    @discardableResult
    public func replaceScript(
        id: String, script: Data, maximumSourceBytes: Int
    ) throws -> Addon {
        try validate(id)
        guard script.count <= maximumSourceBytes else {
            throw StoreError.scriptTooLarge(limit: maximumSourceBytes)
        }
        guard fileManager.fileExists(atPath: scriptURL(id: id).path) else {
            throw StoreError.missingScript
        }
        try writeScript(script, for: id)
        var addon = try load(id: id)
        var state = addon.state
        state.scriptDigest = Self.digest(script)
        state.scriptByteCount = script.count
        state.updatedAt = Date()
        try writeState(state, to: stateURL(id: id))
        addon = try load(id: id)
        return addon
    }

    public func updateState(_ state: ScriptAddonState) throws {
        try validate(state.id)
        try writeState(state, to: stateURL(id: state.id))
    }

    public func setEnabled(_ enabled: Bool, id: String) throws {
        try mutate(id: id) { $0.enabled = enabled }
    }

    public func setOrder(_ order: Int, id: String) throws {
        try mutate(id: id) { $0.order = order }
    }

    public func reorder(_ ids: [String]) throws {
        for (index, id) in ids.enumerated() {
            try setOrder(index, id: id)
        }
    }

    public func updateSetting(key: String, value: String, id: String) throws {
        try mutate(id: id) { $0.settings[key] = value }
    }

    public func removeSetting(key: String, id: String) throws {
        try mutate(id: id) { $0.settings.removeValue(forKey: key) }
    }

    public func confirm(declarations: ScriptDeclarations, id: String) throws {
        let digest = try declarations.confirmationDigest()
        try mutate(id: id) { $0.confirmedDigest = digest }
    }

    public func delete(id: String) throws {
        try validate(id)
        let directory = root.appendingPathComponent(id, isDirectory: true)
        if fileManager.fileExists(atPath: directory.path) {
            try fileManager.removeItem(at: directory)
        }
    }

    /// True when the script's declarations changed since the user confirmed them:
    /// new connect hosts, settings, secrets or an audio requirement ask again.
    public func needsReconfirmation(id: String, declarations: ScriptDeclarations) throws -> Bool {
        let state = try load(id: id).state
        let digest = try declarations.confirmationDigest()
        return state.confirmedDigest != digest
    }

    public func exportData(id: String) throws -> Data {
        try scriptBytes(id: id)
    }

    // MARK: - Internals

    /// Writes script.js atomically even when the target already exists (edit, or a
    /// second import with the same identifier).
    private func writeScript(_ script: Data, for id: String) throws {
        let directory = root.appendingPathComponent(id, isDirectory: true)
        let temporary = directory.appendingPathComponent("script.js.tmp")
        try script.write(to: temporary, options: .atomic)
        let target = scriptURL(id: id)
        if fileManager.fileExists(atPath: target.path) {
            _ = try fileManager.replaceItemAt(target, withItemAt: temporary)
        } else {
            try fileManager.moveItem(at: temporary, to: target)
        }
    }

    private func mutate(id: String, _ body: (inout ScriptAddonState) -> Void) throws {
        let addon = try load(id: id)
        var state = addon.state
        body(&state)
        state.updatedAt = Date()
        try writeState(state, to: stateURL(id: id))
    }

    private func writeState(_ state: ScriptAddonState, to url: URL) throws {
        var encoded = state
        encoded.schemaVersion = ScriptAddonState.currentSchemaVersion
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        encoder.dateEncodingStrategy = .iso8601
        try encoder.encode(encoded).write(to: url, options: .atomic)
    }

    private func validate(_ id: String) throws {
        guard !id.isEmpty, id.allSatisfy({ $0.isLetter || $0.isNumber || $0 == "-" || $0 == "_" })
        else { throw StoreError.invalidIdentifier }
        guard !id.hasPrefix(".") else { throw StoreError.invalidIdentifier }
    }

    private func scriptURL(id: String) -> URL {
        root.appendingPathComponent(id, isDirectory: true).appendingPathComponent("script.js")
    }

    private func stateURL(id: String) -> URL {
        root.appendingPathComponent(id, isDirectory: true).appendingPathComponent("state.json")
    }

    public static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
